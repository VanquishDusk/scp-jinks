export const GLYPH_W = 5;
export const GLYPH_H = 7;

export function textWidth(text, scale = 1) {
  return text.length ? (text.length * (GLYPH_W + 1) - 1) * scale : 0;
}

/**
 * Draw pixel text on a 2D canvas context.
 * align: 'left' | 'center' | 'right' relative to x.
 */
export function drawPixelText(ctx, text, x, y, scale, color, align = 'left') {
  const str = String(text).toUpperCase();
  const w = textWidth(str, scale);
  let cx = Math.round(align === 'center' ? x - w / 2 : align === 'right' ? x - w : x);
  const cy = Math.round(y);
  ctx.fillStyle = color;
  for (const ch of str) {
    const glyph = G[ch] || G['?'];
    for (let row = 0; row < GLYPH_H; row++) {
      const bits = glyph[row];
      for (let col = 0; col < GLYPH_W; col++) {
        if (bits & (1 << (GLYPH_W - 1 - col))) {
          ctx.fillRect(cx + col * scale, cy + row * scale, scale, scale);
        }
      }
    }
    cx += (GLYPH_W + 1) * scale;
  }
}
